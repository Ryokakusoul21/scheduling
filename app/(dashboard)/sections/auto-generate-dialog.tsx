"use client";

import { useId, useState, useTransition } from "react";
import Link from "next/link";
import { toast } from "sonner";
import { Sparkle } from "@phosphor-icons/react/ssr";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Dialog, DialogContent, DialogDescription, DialogFooter, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { Input } from "@/components/ui/input";
import { NativeSelect } from "@/components/ux/native-select";
import { planSectionGeneration, type SectionGenerationContext } from "@/lib/sections/generation";
import { generateSectionsAction, loadSectionGenerationContextAction, undoSectionGenerationAction } from "./actions";

export function AutoGenerateDialog({ program, yearLevel, yearNumber, term, largestRoomCapacity, disabled }: {
  program: { id: string; code: string; name: string }; yearLevel: string; yearNumber: number; term: { id: string; label: string };
  largestRoomCapacity: number; disabled?: boolean;
}) {
  const uid = useId();
  const [open, setOpen] = useState(false);
  const [total, setTotal] = useState("106");
  const [maximum, setMaximum] = useState("40");
  const [balanced, setBalanced] = useState(true);
  const [pattern, setPattern] = useState<"NAME" | "CODE">("CODE");
  const [linkCurriculum, setLinkCurriculum] = useState(true);
  const [mode, setMode] = useState<"ADD" | "REBALANCE">("ADD");
  const [context, setContext] = useState<SectionGenerationContext | null>(null);
  const [error, setError] = useState("");
  const [pending, startTransition] = useTransition();
  const [batch, setBatch] = useState<{ id: string; created: number; updated: number; total: number } | null>(null);
  const plan = context ? planSectionGeneration({
    totalLearners: Number(total), maximum: Number(maximum), balanced, mode,
    prefix: pattern === "NAME" ? program.name : program.code, yearNumber,
  }, context.existing, context.reservedNames) : null;
  const hasChanges = plan?.ok && (plan.created > 0 || plan.updated > 0);

  function reload(resetTotal = false) {
    setError(""); setContext(null);
    startTransition(async () => {
      try {
        const result = await loadSectionGenerationContextAction({ programId: program.id, yearLevel, semesterId: term.id });
        if (!result.ok) { setError(result.error); return; }
        setContext(result.context);
        if (resetTotal) setTotal(String(result.context.existing.reduce((sum, s) => sum + s.studentCount, 0) || 106));
      } catch { setError("Could not load the preview. Please retry."); }
    });
  }

  function onOpenChange(next: boolean) {
    if (pending) return;
    setOpen(next);
    if (next && !batch) reload(true);
  }

  function submit() {
    if (!context || !hasChanges || pending) return;
    setError("");
    startTransition(async () => {
      try {
        const result = await generateSectionsAction({ programId: program.id, yearLevel, semesterId: term.id,
          totalLearners: Number(total), maximum: Number(maximum), balanced, mode, pattern, linkCurriculum, fingerprint: context.fingerprint,
        });
        if (!result.ok) { setError(result.error); return; }
        setBatch({ id: result.batchId, created: result.created, updated: result.updated, total: result.total });
        toast.success(`${result.created} new section(s), ${result.updated} updated.`);
      } catch { setError("Could not generate sections. Your settings are still here; please retry."); }
    });
  }

  function undo() {
    if (!batch || pending) return;
    setError("");
    startTransition(async () => {
      try {
        const result = await undoSectionGenerationAction(batch.id);
        if (!result.ok) { setError(result.error); return; }
        toast.success("New sections removed and previous planning counts restored.");
        setBatch(null); setContext(null); setOpen(false);
      } catch { setError("Could not undo this batch. Please retry."); }
    });
  }

  return (
    <>
      <Button variant="outline" disabled={disabled} onClick={() => onOpenChange(true)}><Sparkle className="size-4" /> Auto-generate sections</Button>
      <Dialog open={open} onOpenChange={onOpenChange}>
        <DialogContent className="max-h-[90dvh] overflow-y-auto sm:max-w-3xl">
          <DialogHeader>
            <DialogTitle className="text-lg font-bold">Auto-generate sections</DialogTitle>
            <DialogDescription>Plan section sizes without moving enrolled students or changing class schedules.</DialogDescription>
          </DialogHeader>
          {batch ? (
            <div className="space-y-4 rounded-xl border bg-muted/40 p-4">
              <p role="status" className="font-semibold">{batch.created} new sections · {batch.updated} updated · {batch.total} students total</p>
              <p className="text-sm text-muted-foreground">Only previewed changes were saved. Undo while unchanged and unused.</p>
              <div className="flex flex-wrap gap-2">
                <Button nativeButton={false} render={<Link href="/scheduler" />}>Open Scheduler</Button>
                <Button variant="outline" disabled={pending} onClick={undo}>Undo generation</Button>
                <Button variant="ghost" disabled={pending} onClick={() => { setBatch(null); reload(true); }}>Generate again</Button>
              </div>
            </div>
          ) : (
            <>
              <div className="rounded-lg bg-muted/40 p-3 text-sm">
                <p className="font-semibold">{program.code} · Year {yearNumber}</p>
                <p className="text-muted-foreground">{program.name} · {term.label}</p>
              </div>
              <div className="grid gap-4 sm:grid-cols-2">
                <div className="space-y-1.5">
                  <label htmlFor={uid + "-total"} className="text-sm font-medium">Total students in this cohort</label>
                  <Input id={uid + "-total"} type="number" min={1} max={10000} step={1} value={total} disabled={pending} onChange={(e) => setTotal(e.target.value)} aria-describedby={uid + "-total-help"} />
                  <p id={uid + "-total-help"} className="text-xs text-muted-foreground">Includes the {plan?.currentTotal ?? 0} students already counted in existing sections.</p>
                </div>
                <div className="space-y-1.5">
                  <label htmlFor={uid + "-maximum"} className="text-sm font-medium">Maximum students per section</label>
                  <Input id={uid + "-maximum"} type="number" min={1} max={500} step={1} value={maximum} disabled={pending} onChange={(e) => setMaximum(e.target.value)} />
                  <p className="text-xs text-muted-foreground">{mode === "ADD" ? "Applies to new sections. Existing counts stay unchanged." : "Applies to every proposed section count."}</p>
                  {Number(maximum) > largestRoomCapacity && <p className="text-xs text-amber-700 dark:text-amber-400">The largest available room holds {largestRoomCapacity} students. Check room capacity before scheduling.</p>}
                </div>
              </div>
              <fieldset className="space-y-2 rounded-lg border p-3" disabled={pending}>
                <legend className="px-1 text-sm font-semibold">Student distribution</legend>
                <label className="flex items-start gap-2 text-sm"><input type="radio" name={uid + "-distribution"} className="mt-1 accent-primary" checked={balanced} onChange={() => setBalanced(true)} /> Balanced sizes (recommended)</label>
                <label className="flex items-start gap-2 text-sm"><input type="radio" name={uid + "-distribution"} className="mt-1 accent-primary" checked={!balanced} onChange={() => setBalanced(false)} /> Fill sections to the maximum; place the remainder in the last section</label>
              </fieldset>
              <fieldset className="space-y-2 rounded-lg border p-3" disabled={pending}>
                <legend className="px-1 text-sm font-semibold">Existing sections</legend>
                <label className="flex items-start gap-2 text-sm"><input type="radio" name={uid + "-mode"} className="mt-1 accent-primary" checked={mode === "ADD"} onChange={() => setMode("ADD")} /> Add new sections only; continue from the next letter</label>
                <label className="flex items-start gap-2 text-sm"><input type="radio" name={uid + "-mode"} className="mt-1 accent-primary" checked={mode === "REBALANCE"} disabled={!context?.existing.length} onChange={() => setMode("REBALANCE")} /> Rebalance all sections, including existing ones</label>
                <p className="text-xs text-muted-foreground">{mode === "ADD" ? "Existing names and counts are preserved. Only the remaining students go into new sections." : "Existing names stay the same. Only planning counts change; enrolled students stay in their sections."}</p>
              </fieldset>
              <div className="flex flex-wrap items-end justify-between gap-3">
                <label className="space-y-1 text-sm font-medium">Naming pattern<NativeSelect value={pattern} disabled={pending} onChange={(e) => setPattern(e.target.value as "NAME" | "CODE")} options={[{ value: "CODE", label: "Code + year-letter" }, { value: "NAME", label: "Program name + year-letter" }]} /></label>
                <Button variant="ghost" size="sm" disabled={pending} onClick={() => reload()}>Refresh preview</Button>
              </div>
              <label className="flex items-start gap-2 text-sm"><input type="checkbox" className="mt-1 accent-primary" disabled={pending} checked={linkCurriculum} onChange={(e) => setLinkCurriculum(e.target.checked)} /> Link curriculum subjects to new sections ({context?.curriculumClasses ?? 0} class placeholders per new section)</label>
              {!context && pending && <p role="status" className="py-5 text-center text-sm text-muted-foreground">Loading current sections…</p>}
              {plan && !plan.ok && <p role="alert" className="text-sm text-destructive">{plan.error}</p>}
              {plan?.ok && (
                <>
                  <p role="status" className="rounded-lg bg-primary/5 p-3 text-sm font-medium">{plan.unchanged} existing unchanged · {plan.updated} updated · {plan.created} new · {plan.total} students total</p>
                  {mode === "ADD" && <p className="text-xs text-muted-foreground">{plan.currentTotal} already counted · {plan.remaining} remaining for new sections. Archived section letters are reserved.</p>}
                  <div className="max-h-72 overflow-auto rounded-lg border">
                    <table className="w-full min-w-[32rem] text-sm">
                      <caption className="sr-only">Section planning preview: current counts, proposed counts, and changes</caption>
                      <thead className="sticky top-0 bg-muted"><tr><th className="p-2 text-left">Section</th><th className="p-2 text-right">Current students</th><th className="p-2 text-right">Proposed students</th><th className="p-2 text-left">Status</th><th className="p-2 text-right">Classes to link</th></tr></thead>
                      <tbody>{plan.rows.map((row) => <tr key={row.id ?? row.name} className="border-t">
                        <td className="p-2 font-medium">{row.name}</td><td className="p-2 text-right tabular-nums">{row.current ?? "—"}</td><td className="p-2 text-right tabular-nums">{row.proposed}</td>
                        <td className="p-2"><Badge variant={row.status === "NEW" ? "default" : "secondary"}>{row.status === "NEW" ? "New" : row.status === "UPDATED" ? "Updated" : "Unchanged"}</Badge></td>
                        <td className="p-2 text-right">{row.status === "NEW" && linkCurriculum ? context?.curriculumClasses : "—"}</td>
                      </tr>)}</tbody>
                    </table>
                  </div>
                  {!hasChanges && <p className="text-sm text-muted-foreground">{mode === "ADD" ? "All students are already accounted for. Increase the cohort total to add sections, or choose Rebalance all sections." : "The existing counts already match these settings."}</p>}
                </>
              )}
              <DialogFooter><Button variant="outline" disabled={pending} onClick={() => setOpen(false)}>Cancel</Button><Button onClick={submit} disabled={!hasChanges || pending}>{pending ? "Working…" : "Confirm and generate"}</Button></DialogFooter>
            </>
          )}
          {error && <p role="alert" className="text-sm text-destructive">{error}</p>}
        </DialogContent>
      </Dialog>
    </>
  );
}
