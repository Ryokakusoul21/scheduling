"use client";

import Link from "next/link";
import { useSearchParams } from "next/navigation";
import { CalendarDots, Lock, Plus, UsersThree, Warning } from "@phosphor-icons/react/ssr";
import { useMemo, useState } from "react";
import { DownloadSimple, MagnifyingGlass } from "@phosphor-icons/react/ssr";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { NativeSelect } from "@/components/ux/native-select";
import { downloadText, toCsv } from "@/lib/export/csv";
import { ActionButton } from "@/components/ux/action-button";
import { Badge } from "@/components/ui/badge";
import { FormDialog, useDialogState, type FormField } from "@/components/ux/form-dialog";
import { ArchiveButton } from "@/components/ux/archive-button";
import { DragHandle, SortableList } from "@/components/ux/sortable-list";
import { EmptyState } from "@/components/ux/states";
import { useShortcut } from "@/components/ux/shortcuts";
import { useRovingFocus } from "@/hooks/use-roving-focus";
import { reorderAction } from "@/actions/reorder";
import { LEVELS, gradeLabel, type AcademicLevel } from "@/lib/academics/levels";
import { cn } from "@/lib/utils";
import { saveSectionAction } from "./actions";
import { AutoGenerateDialog } from "./auto-generate-dialog";
import { Progress } from "@/components/ui/progress";
import { CollectionView, RecordsTable } from "@/components/ux/collection-view";

export interface SectionRow {
  id: string;
  name: string;
  studentCount: number;
  level: string;
  programId: string;
  program: string | null;
  yearLevel: string;
  gradeLevel: string;
  semesterId: string;
  term: string | null;
  classes: number;
  scheduled?: number;
  assignedCapacity?: number;
  editable?: boolean;
  programName?: string | null;
}

export function SectionsGrid({
  heading,
  context,
  sections,
  strands,
  terms,
  canManage = true,
  currentTerm,
  generation,
}: {
  heading: string;
  context: { level: string; programId: string; yearLevel: string; gradeLevel: string; semesterId?: string };
  sections: SectionRow[];
  strands: { value: string; label: string }[];
  terms: { value: string; label: string }[];
  canManage?: boolean;
  currentTerm?: { id: string; label: string };
  generation?: { program: { id: string; code: string; name: string }; yearNumber: number; curriculumClasses: number; largestRoomCapacity: number };
}) {
  const dialog = useDialogState<SectionRow>();
  const { ref, onKeyDown, onFocus } = useRovingFocus({ orientation: "grid" });
  const level = context.level as AcademicLevel;
  const isCollege = level === "COLLEGE";
  const searchParams = useSearchParams();
  const allowManage = canManage && searchParams.get("status") !== "ARCHIVED";

  const [query, setQuery] = useState("");
  const [filter, setFilter] = useState("");
  const [sort, setSort] = useState("order");
  const filtersOn = !!(query || filter || sort !== "order");
  const allSections = sections;
  const shown = useMemo(() => {
    const q = query.trim().toLowerCase();
    const open = (x: SectionRow) => x.classes - (x.scheduled ?? 0);
    return allSections
      .filter((x) => (!q || `${x.name} ${x.program ?? ""}`.toLowerCase().includes(q)) && (filter === "UNSCHEDULED" ? open(x) > 0 : filter === "OVER" ? !!x.assignedCapacity && x.studentCount > x.assignedCapacity : true))
      .sort((a, b) => (sort === "name" ? a.name.localeCompare(b.name, undefined, { numeric: true }) : sort === "learners" ? b.studentCount - a.studentCount : sort === "unscheduled" ? open(b) - open(a) : 0));
  }, [allSections, query, filter, sort]);
  const reorder = (ids: string[]) => (filtersOn ? Promise.resolve({ ok: false, error: "Clear search, filter, and sort to reorder." }) : reorderAction("section", ids));
  const exportCsv = () => downloadText(`${heading.replace(/[^\w]+/g, "-").toLowerCase()}-sections.csv`, toCsv(shown, [
    { header: "Section", value: (x) => x.name }, { header: "Program", value: (x) => x.program }, { header: "Learners", value: (x) => x.studentCount },
    { header: "Term", value: (x) => x.term }, { header: "Scheduled classes", value: (x) => x.scheduled ?? 0 }, { header: "Total classes", value: (x) => x.classes },
  ]));

  useShortcut({ keys: "n", description: "Add a section", group: "Sections", handler: () => allowManage && dialog.openCreate() });

  const editing = dialog.state?.mode === "edit" ? dialog.state.item : null;
  const fields: FormField[] = [
    { name: "level", label: "", type: "hidden" },
    ...(isCollege
      ? [
          { name: "programId", label: "", type: "hidden" as const },
          { name: "yearLevel", label: "", type: "hidden" as const },
        ]
      : []),
    { name: "name", label: "Section name", type: "text", required: true, placeholder: isCollege ? "BSIT 1C" : level === "SENIOR_HIGH" ? "11-STEM B" : `${gradeLabel(context.gradeLevel)} - A` },
    { name: "studentCount", label: "Number of learners", type: "number", min: 0, required: true, help: "Used to check room capacity in the Scheduler." },
    ...(!isCollege
      ? [
          {
            name: "gradeLevel",
            label: "Grade level",
            type: "select" as const,
            required: true,
            options: LEVELS[level].grades.map((g) => ({ value: g, label: gradeLabel(g) })),
          },
        ]
      : []),
    ...(level === "SENIOR_HIGH"
      ? [{ name: "programId", label: "Strand", type: "select" as const, required: true, options: [{ value: "", label: "Select strand" }, ...strands] }]
      : []),
    ...(isCollege
      ? [{ name: "semesterId", label: "Term (optional)", type: "select" as const, options: [{ value: "", label: "Not tied to a term" }, ...terms] }]
      : []),
  ];

  return (
    <section aria-label={heading} className="space-y-3">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div>
          <h2 className="font-semibold">{heading}</h2>
          <p className="text-xs text-muted-foreground">
            {sections.length} sections · {sections.reduce((s, x) => s + x.studentCount, 0)} learners · drag the handle to reorder
          </p>
        </div>
        <div className="flex flex-wrap gap-2">{generation && currentTerm && <AutoGenerateDialog program={generation.program} yearLevel={context.yearLevel} yearNumber={generation.yearNumber} term={currentTerm} largestRoomCapacity={generation.largestRoomCapacity} disabled={!allowManage} />}<Button onClick={dialog.openCreate} disabled={!allowManage} aria-keyshortcuts="n"><Plus className="size-4" /> Add section</Button></div>
      </div>

      {sections.length === 0 ? (
        <EmptyState
          icon={UsersThree}
          title="No sections for this term yet"
          description="Create sections for the selected academic year and semester so they can be scheduled."
          action={<div className="flex flex-wrap gap-2">{generation && currentTerm && <AutoGenerateDialog program={generation.program} yearLevel={context.yearLevel} yearNumber={generation.yearNumber} term={currentTerm} largestRoomCapacity={generation.largestRoomCapacity} disabled={!allowManage} />}<Button onClick={dialog.openCreate} disabled={!allowManage}>Add section</Button></div>}
        />
      ) : (
        <>
        <div className="flex flex-wrap items-center gap-2 print:hidden">
          <div className="relative min-w-48 flex-1">
            <MagnifyingGlass className="pointer-events-none absolute top-1/2 left-2.5 size-4 -translate-y-1/2 text-muted-foreground" />
            <Input type="search" aria-label="Search sections" placeholder="Search section or program" className="pl-8" value={query} onChange={(e) => setQuery(e.target.value)} />
          </div>
          <NativeSelect aria-label="Filter sections" className="w-44" value={filter} onChange={(e) => setFilter(e.target.value)} placeholder="All sections" options={[{ value: "UNSCHEDULED", label: "Has unscheduled classes" }, { value: "OVER", label: "Exceeds room capacity" }]} />
          <NativeSelect aria-label="Sort sections" className="w-44" value={sort} onChange={(e) => setSort(e.target.value)} options={[{ value: "order", label: "Custom order" }, { value: "name", label: "Name" }, { value: "learners", label: "Most learners" }, { value: "unscheduled", label: "Most unscheduled" }]} />
          <Button type="button" variant="outline" onClick={exportCsv} disabled={!shown.length}><DownloadSimple className="size-4" /> Export spreadsheet</Button>
        </div>
        {shown.length === 0 && <p className="rounded-xl border border-dashed p-6 text-center text-sm text-muted-foreground">No sections match your search or filter.</p>}
        <CollectionView storageKey="sections:view" label="Sections" table={<RecordsTable label={heading} columns={["Section", "Program", "Learners", "Term", "Scheduling", "Actions"]} rows={shown.map((s) => ({ id: s.id, label: s.name, draggable: allowManage && (s.editable ?? canManage), cells: [<span key="name" className="font-semibold">{s.name}</span>, s.program ?? "—", <span key="learners">{s.studentCount}{!!s.assignedCapacity && s.studentCount > s.assignedCapacity && <span className="block text-xs text-amber-700">Exceeds room capacity</span>}</span>, s.term ?? "—", `${s.scheduled ?? 0}/${s.classes} scheduled`, <div key="actions" className="flex items-center gap-1.5"><Link href={`/scheduler?level=${s.level}&sectionId=${s.id}`} className="text-primary hover:underline">Timetable</Link>{allowManage && (s.editable ?? canManage) ? <><ActionButton kind="edit" onClick={() => dialog.openEdit(s)}>Edit</ActionButton><ArchiveButton kind="SECTION" id={s.id} name={s.name} /></> : <Badge variant="outline">Read-only</Badge>}</div>] }))} onReorder={allowManage ? reorder : undefined} />}>
        <div ref={ref} onKeyDown={onKeyDown} onFocus={onFocus} className="grid gap-3 sm:grid-cols-2 xl:grid-cols-3">
          <SortableList
            items={shown}
            layout="grid"
            getLabel={(s) => s.name}
            onReorder={reorder}
            renderItem={(s, { setNodeRef, style, isDragging, handleProps }) => (
              <div
                ref={setNodeRef}
                style={style}
                className={cn("rounded-xl border bg-card p-4 shadow-xs transition-shadow hover:shadow-md", isDragging && "shadow-lg ring-2 ring-primary")}
              >
                <div className="flex items-start gap-2">
                  {allowManage && (s.editable ?? canManage) ? <DragHandle {...handleProps} className="-ml-1" /> : <Lock className="mt-1 size-4 text-muted-foreground" aria-label="Read-only" />}
                  <button
                    type="button"
                    data-roving=""
                    tabIndex={-1}
                    onClick={() => allowManage && (s.editable ?? canManage) && dialog.openEdit(s)}
                    className="min-w-0 flex-1 rounded text-left outline-none"
                    aria-label={`${s.name}, ${s.studentCount} learners.${(s.editable ?? canManage) ? " Press Enter to edit." : " Read-only."}`}
                  >
                    <p className="truncate font-semibold">{s.name}</p>
                    <p className="text-sm text-muted-foreground">{s.studentCount} learners</p>
                  </button>
                  {allowManage && (s.editable ?? canManage) ? <div className="flex shrink-0 items-center justify-end gap-1.5 whitespace-nowrap">
                    <ActionButton kind="edit" onClick={() => dialog.openEdit(s)}>
                      Edit
                    </ActionButton>
                    <ArchiveButton kind="SECTION" id={s.id} name={s.name} />
                  </div> : <Badge variant="outline"><Lock className="mr-1 size-3" /> Read-only</Badge>}
                </div>
                <div className="mt-3 flex flex-wrap items-center gap-1.5">
                  {s.program && <Badge variant="secondary" title={s.programName ?? undefined}>{s.program}</Badge>}
                  {s.term && <Badge variant="outline">{s.term}</Badge>}
                  <Link href={`/scheduler?level=${s.level}&sectionId=${s.id}`}><Badge variant={s.classes > 0 && (s.scheduled ?? 0) === s.classes ? "default" : "secondary"}>{s.classes > 0 && (s.scheduled ?? 0) === s.classes ? "Fully scheduled" : `${s.classes} classes · ${s.scheduled ?? 0} scheduled`}</Badge></Link>
                  {s.classes - (s.scheduled ?? 0) > 0 && <Badge className="border-amber-500/40 bg-amber-500/10 text-amber-800 dark:text-amber-300" variant="outline"><Warning className="mr-1 size-3" />{s.classes - (s.scheduled ?? 0)} unscheduled</Badge>}
                  <Link
                    href={`/scheduler?level=${s.level}&sectionId=${s.id}`}
                    className="ml-auto inline-flex items-center gap-1 rounded text-xs font-medium text-primary hover:underline"
                  >
                    <CalendarDots className="size-3.5" /> Timetable
                  </Link>
                </div>
                <div className="mt-3 flex items-center gap-2"><Progress aria-label="Scheduling progress" value={s.classes ? Math.round(((s.scheduled ?? 0) / s.classes) * 100) : 0} className="flex-1" /><span className="text-xs text-muted-foreground">{s.classes ? Math.round(((s.scheduled ?? 0) / s.classes) * 100) : 0}% scheduled</span></div>
                {!!s.assignedCapacity && s.studentCount > s.assignedCapacity && <p className="mt-2 flex items-center gap-1 text-xs font-medium text-amber-700 dark:text-amber-300"><Warning className="size-3.5" /> Learners exceed room capacity</p>}
              </div>
            )}
          />
        </div>
        </CollectionView>
        </>
      )}

      <FormDialog
        open={!!dialog.state}
        onOpenChange={(o) => !o && dialog.close()}
        title={editing ? `Edit ${editing.name}` : "Add section"}
        description={heading}
        fields={fields}
        values={editing ?? { ...context, semesterId: context.semesterId ?? "", studentCount: 40 }}
        submitLabel={editing ? "Save changes" : "Add section"}
        successMessage={editing ? "Section updated" : "Section added"}
        onSubmit={(fd) => saveSectionAction(editing?.id ?? null, fd)}
      />
    </section>
  );
}
